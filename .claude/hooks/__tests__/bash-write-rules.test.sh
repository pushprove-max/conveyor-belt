#!/usr/bin/env bash
# SPDX-License-Identifier: Apache-2.0
# Self-test for bash-write-rules.sh: Claude Code loads a path rule only
# for Read/Edit/Write, so a shell write into a rule's paths must get the rule
# from the hook instead -- once per session per rule -- and the inlined policy
# text must ride along. Fixture paths are scratch names; no file is written.
# The hook runs from a fixture install that holds no rules, as a plugin's does,
# for a fixture project holding its own rule files (their paths: globs are the
# path-to-rule map), never this repo's .claude/rules/, so the test passes in any
# repo and a hook that read the rules beside itself would give nothing.
# Run: bash .claude/hooks/__tests__/bash-write-rules.test.sh
set -u
ROOT="$(cd "$(dirname "$0")/../../.." && pwd)"
SID="bashwriterules-$$"
PASS=0; FAIL=0
FX=$(mktemp -d); FX=$(cd "$FX" && pwd -P)
INST=$(mktemp -d); INST=$(cd "$INST" && pwd -P)
trap 'rm -rf "$FX" "$INST"; rm -f /tmp/claude-bash-rules-*-"$SID"-*' EXIT
check() { if [ "$2" = "$3" ]; then PASS=$((PASS+1)); echo "ok   $1"; else FAIL=$((FAIL+1)); echo "FAIL $1 (expected $2, got $3)"; fi; }
has() { case "$1" in *"$2"*) echo yes ;; *) echo no ;; esac; }

# The fixture install: the hook and its lib. The fixture project: four rules. backend.md and tests.md each carry a
# generated policy section behind hand-written prose, sized so either fits under the cap beside comments.md but not
# beside the other; zz-big.md is over the cap with no generated section.
mkdir -p "$INST/.claude/hooks/lib" "$FX/.claude/rules"
cp "$ROOT/.claude/hooks/bash-write-rules.sh" "$INST/.claude/hooks/"; cp "$ROOT/.claude/hooks/lib/strip-quoted.sh" "$INST/.claude/hooks/lib/"
HOOK="$INST/.claude/hooks/bash-write-rules.sh"
BANNER='<!-- GENERATED by policy/generate.sh: do not edit below -->'
pad() { local i; for ((i = 0; i < $1; i++)); do printf 'policy line %04d\n' "$i"; done; }
{ printf -- '---\npaths:\n  - "src/**/*.ts"\n  - "lambdas/**/*.ts"\n  - "shared/**/*.ts"\n---\n# Backend\n\nBACKEND-HAND-WRITTEN-PROSE\n\n%s\n' "$BANNER"
  printf '# API and Data Conventions\n'; pad 160; printf '# Security Review Policy\n'; pad 160; } > "$FX/.claude/rules/backend.md"
{ printf -- '---\npaths: ["**/__tests__/**/*.test.ts", "**/*.test.ts"]\n---\nTESTS-HAND-WRITTEN-PROSE\n\n%s\n' "$BANNER"
  printf '# Test Standards\n\n## Running tests\n'; pad 320; } > "$FX/.claude/rules/tests.md"
printf -- '---\npaths:\n  - "**/*.ts"\n---\n# Code comments\n\nSay why, not what.\n' > "$FX/.claude/rules/comments.md"
{ printf -- '---\npaths:\n  - "docs/zz-fixture/**"\n---\n'; head -c 12000 /dev/zero | tr '\0' 'x'; } > "$FX/.claude/rules/zz-big.md"

# session command -> the injected text, empty when none
ctx() {
  jq -cn --arg s "$SID-$1" --arg c "$2" --arg cwd "$FX" \
    '{session_id:$s, cwd:$cwd, hook_event_name:"PreToolUse", tool_name:"Bash", tool_input:{command:$c}}' \
    | CLAUDE_PROJECT_DIR="$FX" bash "$HOOK" 2>/dev/null | jq -r '.hookSpecificOutput.additionalContext // empty'
}
# Claude Code saves hook output over 10,000 chars to disk and shows a 2,000-char
# preview, so a longer injection never reaches the model as policy text.
fits() { [ "${#1}" -gt 0 ] && [ "${#1}" -lt 10000 ] && echo yes || echo "no (${#1} chars)"; }

OUT=$(ctx a "cat > src/zz-bwr-scratch.ts <<'EOF'
export const a = 1;
EOF")
check "a heredoc write into src injects backend.md"            yes "$(has "$OUT" 'Read .claude/rules/backend.md')"
check "  without the rule's hand-written prose"                no "$(has "$OUT" BACKEND-HAND-WRITTEN-PROSE)"
check "  with the generated api-conventions text"              yes "$(has "$OUT" '# API and Data Conventions')"
check "  and the generated security-review text"               yes "$(has "$OUT" '# Security Review Policy')"
check "  under the hook-output cap"                            yes "$(fits "$OUT")"
# The comments.md rule is path-gated on code files, so a shell write to code is its only way in; it rides beside
# backend.md when both fit under the cap.
check "  and comments.md beside it, which a shell write would otherwise never load" yes "$(has "$OUT" '# Code comments')"
check "the same session's next src write injects nothing"      "" "$(ctx a "printf 'x' > src/zz-bwr-other.ts")"

OUT=$(ctx b "python3 -c \"open('scripts/__tests__/zz-bwr-scratch.test.ts', 'w').write('x')\"")
check "a python open(w) on a __tests__ .test.ts injects tests.md" yes "$(has "$OUT" '# Test Standards')"
check "  carrying the generated running-tests section"         yes "$(has "$OUT" '## Running tests')"
check "  without the rule's hand-written prose"                no "$(has "$OUT" TESTS-HAND-WRITTEN-PROSE)"
check "  under the hook-output cap"                            yes "$(fits "$OUT")"
check "  and comments.md beside it, which fits under the cap"  yes "$(has "$OUT" '# Code comments')"
check "the same session's next test write injects nothing"     "" "$(ctx b "echo x >> scripts/__tests__/zz-bwr-scratch.test.ts")"

check "a write under docs injects nothing"                     "" "$(ctx c "echo x > docs/zz-bwr-scratch.md")"
check "a read-only cat of a src file injects nothing"          "" "$(ctx d "cat src/zz-bwr-scratch.ts")"
check "a read whose stderr goes to /dev/null injects nothing"  "" "$(ctx d "cat src/zz-bwr-scratch.ts 2>/dev/null >&2")"

# A target is what the shell writes, never a word in a heredoc body or a
# quoted string, so a note that names a test file loads no test rule.
check "a heredoc body naming a test file injects nothing"      "" "$(ctx k "cat >> docs/zz-bwr-scratch.md <<'EOF'
see src/__tests__/zz-bwr-scratch.test.ts and lambdas/api/zz-bwr.ts
EOF")"
check "a read-only rg for a quoted tee injects nothing"        "" "$(ctx k2 "rg -no 'tee .*>' src/zz-bwr-scratch.ts")"
check "a read whose only write is outside the checkout injects nothing" "" \
  "$(ctx k3 "cat .claude/briefs/_brief-short-template.md > /tmp/zz-bwr-outside/zz-bwr.json")"
check "a heredoc write into a test file injects tests.md"      yes "$(has "$(ctx l "cat > scripts/__tests__/zz-bwr-heredoc.test.ts <<'EOF'
export {};
EOF")" '# Test Standards')"
check "a perl -pi on a src .ts injects backend.md"            yes "$(has "$(ctx n "perl -pi -e 's/a/b/' src/zz-bwr-scratch.ts")" '# API and Data Conventions')"
check "a quoted redirect target still counts"                 yes "$(has "$(ctx m "printf x > \"src/zz-bwr-scratch.ts\"")" '# API and Data Conventions')"

OUT=$(ctx e "sed -i '' 's/a/b/' lambdas/api/zz-bwr-scratch.ts")
check "a sed -i on a lambdas .ts injects backend.md"           yes "$(has "$OUT" 'Read .claude/rules/backend.md')"
check "  with the generated api-conventions text"              yes "$(has "$OUT" '# API and Data Conventions')"
check "  and the generated security-review text"               yes "$(has "$OUT" '# Security Review Policy')"
OUT=$(ctx f "echo x | tee shared/zz-bwr-scratch.ts")
check "a tee into a shared .ts injects backend.md"             yes "$(has "$OUT" 'Read .claude/rules/backend.md')"
check "  with the generated api-conventions text"              yes "$(has "$OUT" '# API and Data Conventions')"
check "  and the generated security-review text"               yes "$(has "$OUT" '# Security Review Policy')"
check "an absolute path under the checkout counts"             yes "$(has "$(ctx g "printf x > $FX/src/zz-bwr-scratch.ts")" '# API and Data Conventions')"

# A src test file matches both rules: one per command keeps each injection under
# the cap, and the second rule lands on the next write.
OUT=$(ctx h "cp /tmp/zz src/__tests__/zz-bwr-scratch.test.ts")
check "a src test write first injects backend.md"              yes "$(has "$OUT" '# API and Data Conventions')"
check "  and not tests.md in the same output"                  no "$(has "$OUT" '# Test Standards')"
check "the next src test write injects tests.md"               yes "$(has "$(ctx h "mv /tmp/zz src/__tests__/zz-bwr-scratch.test.ts")" '# Test Standards')"

check "a write after cd into src injects backend.md"            yes "$(has "$(ctx i "cd src && echo x > zz-bwr-scratch.ts")" '# API and Data Conventions')"

# A rule over the cap with no generated section is a pointer, not a truncated dump the model never sees.
OUT=$(ctx j "echo x > docs/zz-fixture/a.md")
check "a rule over the cap with no generated section is a pointer" yes "$(has "$OUT" 'Read .claude/rules/zz-big.md')"
check "  and carries none of its text" no "$(has "$OUT" xxxxxxxxxx)"
check "  under the hook-output cap"                            yes "$(fits "$OUT")"

# Every injection the hook can emit: one write per glob of every rule, each in a
# fresh session, so a rule the hook stops injecting for its own glob, or that grows
# past the cap, fails here.
N=0
while IFS=$'\t' read -r rule path; do
  N=$((N + 1))
  OUT=$(ctx "all-$N" "echo x > $path")
  check "a write to $path injects .claude/rules/$rule" yes "$(has "$OUT" "matches .claude/rules/$rule.")"
  check "a write to $path (.claude/rules/$rule) fits under the cap" yes "$(fits "$OUT")"
done < <(python3 - "$FX/.claude/rules" <<'PY'
import json, os, re, sys
d = sys.argv[1]
for name in sorted(os.listdir(d)):
    front = re.match(r"---\n(.*?)\n---\n", open(os.path.join(d, name)).read(), re.S)
    lines = front.group(1).splitlines() if front else []
    for i, line in enumerate(lines):
        if not line.startswith("paths:"):
            continue
        globs = json.loads(line[6:]) if line[6:].strip() else [
            l.strip()[1:].strip().strip("\"'") for l in lines[i + 1:] if l.lstrip().startswith("-")]
        for g in globs:
            print(f"{name}\t" + g.replace("**/", "").replace("**", "zz").replace("*", "zz-bwr").replace("?", "z"))
PY
)
check "every rule glob was exercised" 7 "$N"

# Folded from the three bash-write-rules-*.refute.test.sh files.
OUT=$(ctx fold-a "sed -i.bak -e's/a/b/' src/ra-probe.ts")
# Each misses a write target, so a real write loses its path rules: sed -i -e'expr', a numbered fd, a spaced sed script.
check "attached_expression_write_injects" yes "$(has "$OUT" '# API and Data Conventions')"
check "fd_write_injects" "yes yes" \
  "$(has "$(ctx fold-fd1 'printf x 1> src/zz-fd-refute.ts')" '# API and Data Conventions') $(has "$(ctx fold-fd2 'printf x 2> src/zz-fd-refute.ts')" '# API and Data Conventions')"
OUT=$(ctx fold-s "sed -i 's/a b/c/' src/ra-probe.ts")
check "spaced_sed_write_injects" yes "$(has "$OUT" '# API and Data Conventions')"

# A project with no rule files: a shell write into code gets nothing, and the hook says nothing, even when the
# install it runs from holds rules of its own (they are not the project's).
mkdir -p "$FX/bare" "$INST/.claude/rules" && cp "$FX/.claude/rules/backend.md" "$INST/.claude/rules/"
check "a project with no rules says nothing on a write" "" "$(jq -cn --arg s "$SID-bare" --arg cwd "$FX/bare" \
  '{session_id:$s, cwd:$cwd, hook_event_name:"PreToolUse", tool_name:"Bash", tool_input:{command:"echo x > src/zz-bwr.ts"}}' \
  | CLAUDE_PROJECT_DIR="$FX/bare" bash "$HOOK" 2>&1)"

# A project whose rules dir links elsewhere: paths still match from the project, not from where the link points.
mkdir -p "$FX/linked/.claude" "$FX/policies/rules" && cp "$FX/.claude/rules/backend.md" "$FX/policies/rules/"
ln -s "$FX/policies/rules" "$FX/linked/.claude/rules"
check "a project with linked rules gets its rule on a write" yes "$(has "$(jq -cn --arg s "$SID-linked" --arg cwd "$FX/linked" \
  '{session_id:$s, cwd:$cwd, hook_event_name:"PreToolUse", tool_name:"Bash", tool_input:{command:"echo x > src/zz-bwr.ts"}}' \
  | CLAUDE_PROJECT_DIR="$FX/linked" bash "$HOOK" 2>/dev/null | jq -r '.hookSpecificOutput.additionalContext // empty')" '# API and Data Conventions')"

echo "$PASS passed, $FAIL failed"
[ "$FAIL" = 0 ]
